// Generates src/design-system/tokens.css from tokens.json.
// `node scripts/build-tokens.mjs --check` exits 1 if the committed CSS is stale.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { contrast } from './lib/contrast.mjs';

const root = fileURLToPath(new URL('..', import.meta.url));
const tokens = JSON.parse(readFileSync(root + 'src/design-system/tokens.json', 'utf8'));
const out = root + 'src/design-system/tokens.css';
const { color, service, font, provisional: p } = tokens;
const kebab = s => s.replace(/[A-Z]/g, m => '-' + m.toLowerCase());

const lines = [];
const decl = (name, value) => lines.push(`  --${name}: ${value};`);

for (const [k, v] of Object.entries(color)) decl(`color-${kebab(k)}`, v);
lines.push('');
decl('font-heading', font.heading);
decl('font-body', font.body);
lines.push('');
for (const [k, v] of Object.entries(p.typeScale)) decl(`text-${k}`, v);
for (const [k, v] of Object.entries(p.lineHeight)) decl(`leading-${k}`, v);
for (const [k, v] of Object.entries(p.space)) decl(`space-${k}`, v);
decl('gutter', p.gutter);
for (const [k, v] of Object.entries(p.maxWidth)) decl(`max-${k}`, v);
for (const [k, v] of Object.entries(p.radius)) decl(`radius-${k}`, v);
decl('duration-fast', p.motion.durationFast);
decl('duration-base', p.motion.durationBase);
decl('easing', p.motion.easing);
decl('focus-width', p.focus.width);
decl('focus-offset', p.focus.offset);
decl('focus-color', `var(--color-${p.focus.color})`);
decl('focus-color-on-dark', `var(--color-${p.focus.colorOnDark})`);

// Service accents. --accent-text is the accent only where it reaches AA (4.5:1) for
// normal text on both white and ivory; otherwise it falls back to navy (issue #10:
// terracotta and coral must not be used for normal text on white).
const serviceRules = [];
for (const [slug, s] of Object.entries(service)) {
  const hex = color[s.accent];
  const textSafe = Math.min(contrast(hex, color.white), contrast(hex, color.ivory)) >= 4.5;
  const onAccent = contrast(color.white, hex) >= 4.5 ? 'white' : 'navy';
  serviceRules.push(
    `[data-service="${slug}"] {\n` +
    `  --accent: var(--color-${kebab(s.accent)});\n` +
    `  --accent-text: var(--color-${textSafe ? kebab(s.accent) : 'navy'});\n` +
    `  --on-accent: var(--color-${onAccent});\n}`
  );
}

const css = `/* Generated by scripts/build-tokens.mjs from tokens.json — do not edit by hand. */
:root {
${lines.join('\n')}

  --accent: var(--color-blue);
  --accent-text: var(--color-blue);
  --on-accent: var(--color-white);
}

${serviceRules.join('\n\n')}
`;

if (process.argv.includes('--check')) {
  const current = readFileSync(out, 'utf8').replace(/\r\n/g, '\n');
  if (current !== css) {
    console.error('tokens.css is out of date. Run: node scripts/build-tokens.mjs');
    process.exit(1);
  }
  console.log('tokens.css is up to date');
} else {
  writeFileSync(out, css);
  console.log('wrote', out);
}
